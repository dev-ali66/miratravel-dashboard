export function WhatsIncludedPreview({ whatsIncluded, draft }: { whatsIncluded?: any; draft?: any }) {
  const safeInc = whatsIncluded || draft?.whatsIncluded || {}

  const incBadge = getStr(safeInc.badge, "CURATED INCLUSIONS")
  const incTitle = getStr(safeInc.title ?? safeInc.includedTitle, "Everything Crafted for Ultimate Immersion")

  const notIncBadge = getStr(safeInc.notIncludedBadge, "NOT INCLUDED")
  const notIncTitle = getStr(safeInc.exclusionsTitle ?? safeInc.notIncludedTitle, "The following items are not included in your journey package")

  const rawInclusions = safeInc.inclusions || safeInc.items || []
  const inclusions = Array.isArray(rawInclusions) && rawInclusions.length > 0
    ? rawInclusions.map((item: any, i: number) => {
        if (typeof item === "string") {
          const parts = item.split(":")
          return {
            title: parts[0]?.trim() || `Inclusion ${i + 1}`,
            description: parts.slice(1).join(":")?.trim() || item,
          }
        }
        return {
          title: getStr(item.title || item.name, `Inclusion ${i + 1}`),
          description: getStr(item.description, ""),
        }
      })
    : defaultBrandInclusions

  const rawExclusions = safeInc.exclusions || []
  const exclusions = Array.isArray(rawExclusions) && rawExclusions.length > 0
    ? rawExclusions.map((item: any, i: number) => {
        if (typeof item === "string") {
          const parts = item.split(":")
          return {
            title: parts[0]?.trim() || `Exclusion ${i + 1}`,
            description: parts.slice(1).join(":")?.trim() || item,
          }
        }
        return {
          title: getStr(item.title || item.name, `Exclusion ${i + 1}`),
          description: getStr(item.description, ""),
        }
      })
    : defaultBrandNotIncluded

  const importantInfoItems = Array.isArray(safeInc.importantInfo) && safeInc.importantInfo.length > 0
    ? safeInc.importantInfo
    : defaultImportantInfo

  return (
    <div className="w-full flex flex-col gap-12 md:gap-16 lg:gap-20">
      {/* 1. Curated Inclusions Section */}
      <section className="w-full flex flex-col gap-6 md:gap-8">
        <div className="flex flex-col gap-2">
          {incBadge && (
            <span className="text-[#8D6534] text-xs font-semibold tracking-[2px] uppercase">
              {incBadge}
            </span>
          )}
          <h2 className="text-[#222014] font-heading text-2xl md:text-3xl lg:text-4xl font-normal leading-tight">
            {incTitle}
          </h2>
        </div>

        <div className="w-full grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4 md:gap-6">
          {inclusions.map((card: any, idx: number) => {
            const IconComponent = inclusionIcons[idx % inclusionIcons.length]
            return (
              <InclusionCard
                key={idx}
                title={card.title}
                description={card.description}
                icon={<IconComponent />}
              />
            )
          })}
        </div>
      </section>

      {/* 2. What's Not Included Section */}
      <section className="w-full flex flex-col gap-6 md:gap-8 pt-8 border-t border-[#E8E2D8]">
        <div className="flex flex-col gap-2">
          {notIncBadge && (
            <span className="text-[#8D6534] text-xs font-semibold tracking-[2px] uppercase">
              {notIncBadge}
            </span>
          )}
          <h2 className="text-[#222014] font-heading text-2xl md:text-3xl font-normal leading-tight">
            {notIncTitle}
          </h2>
        </div>

        <div className="w-full grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4 md:gap-6">
          {exclusions.map((item: any, idx: number) => (
            <InclusionCard
              key={idx}
              title={item.title}
              description={item.description}
              icon={getNotIncludedIcon(idx, item.title)}
            />
          ))}
        </div>
      </section>

      {/* 3. Important Information Card */}
      <section className="w-full relative p-6 md:p-8 bg-[#7A8475]/10 rounded-none flex flex-col gap-4 overflow-hidden border border-[#7A8475]/20">
        <h3 className="text-[#222014] text-xl md:text-2xl font-normal font-heading leading-tight">
          Important Information
        </h3>
        <div className="flex flex-col gap-2.5 md:gap-3">
          {importantInfoItems.map((info: string, idx: number) => (
            <div key={idx} className="flex items-start gap-2 text-[#464136] text-sm md:text-base font-normal leading-relaxed">
              <span className="select-none shrink-0 text-[#8D6534]">•</span>
              <span>{info}</span>
            </div>
          ))}
        </div>
      </section>
    </div>
  )
}

