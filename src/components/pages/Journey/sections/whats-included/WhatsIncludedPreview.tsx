function getNotIncludedIcon(idx: number, title: string = "") {
  const lower = title.toLowerCase()
  if (lower.includes("flight") || lower.includes("air")) return <FlightIcon />
  if (lower.includes("lunch") || lower.includes("meal") || lower.includes("food")) return <LunchIcon />
  if (lower.includes("insurance")) return <InsuranceIcon />
  if (lower.includes("personal") || lower.includes("expense") || lower.includes("express")) return <PersonalIcon />
  if (lower.includes("tip") || lower.includes("gratuit")) return <TipsIcon />

  const icons = [<FlightIcon key="0" />, <LunchIcon key="1" />, <InsuranceIcon key="2" />, <PersonalIcon key="3" />, <TipsIcon key="4" />]
  return icons[idx % icons.length]
}

